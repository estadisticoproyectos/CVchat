def extraer_texto_pdf(uploaded_file):
    """Extrae texto de un archivo PDF subido usando PyMuPDF."""
    texto = ""
    with fitz.open(stream=uploaded_file.read(), filetype="pdf") as doc:
        for pagina in doc:
            texto += pagina.get_text()
    return texto


def calcular_similitud_tfidf(texto_cv, texto_oferta):
    """Calcula la similitud de Coseno global y por secciones clave."""
    vectorizer = TfidfVectorizer(stop_words="english")
    try:
        tfidf_matrix = vectorizer.fit_transform([texto_cv, texto_oferta])
        sim_global = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])[0][0]
        porcentaje_global = round(sim_global * 100, 2)
    except Exception:
        porcentaje_global = 0.0

    secciones_clave = {
        "Habilidades / Stack Tecnológico": ["python", "sql", "aws", "git", "docker", "pandas", "java", "react", "api", "machine learning", "data", "excel", "power bi"],
        "Experiencia Laboral": ["experiencia", "desarrolló", "lideró", "gestionó", "implementó", "analizó", "responsable", "proyecto"],
        "Educación y Formación": ["universidad", "licenciatura", "grado", "ingeniería", "máster", "curso", "certificación", "bootcamp"]
    }

    afinidad_secciones = {}
    for nombre_sec, palabras in secciones_clave.items():
        coincidencias = sum(1 for p in palabras if p in texto_cv.lower())
        total_p = len(palabras)
        score_sec = round((coincidencias / total_p) * 100, 1)
        afinidad_secciones[nombre_sec] = min(max(score_sec + 20, 35.0), 98.0) if coincidencias > 0 else 45.0

    return porcentaje_global, afinidad_secciones


def llamar_gemini_con_respaldo(prompt, modelo_principal):
    """Ejecuta llamadas a Gemini con respaldo de modelos y reintentos automáticos ante errores 503."""
    modelos_a_probar = list(
        dict.fromkeys(["gemini-3.5-flash-lite", str(modelo_principal).strip(), "gemini-3.8-flash"])
    )

    config_rapida = {"max_output_tokens": 1500}
    ultimo_error = None

    for modelo_actual in modelos_a_probar:
        for intento in range(3):
            try:
                resp = client.models.generate_content(
                    model=modelo_actual, contents=prompt, config=config_rapida
                )
                if resp and resp.text:
                    return resp.text
            except Exception as e:
                ultimo_error = e
                if "503" in str(e) or "UNAVAILABLE" in str(e):
                    time.sleep(2 + intento * 2)
                    continue
                else:
                    break

    raise Exception(f"Todos los modelos fallaron o siguen saturados. Último error: {ultimo_error}")


def extraer_variables_ciencia_datos(texto_cv, texto_oferta, modelo):
    """Extrae metadatos y variables estructuradas para análisis de datos y perfilamiento."""
    prompt_variables = f"""
    Analiza el siguiente Currículum Vitae y la Descripción del Trabajo para extraer métricas clave.
    Responde estrictamente en formato JSON válido con las siguientes claves:
    - "puesto_objetivo": (string, título del puesto al que postula o el rol principal detectado)
    - "nivel_jerarquico": (string, ej: Junior, Semi-Senior, Senior, Lead)
    - "edad": (entero o null si no se deduce)
    - "busqueda_primera_vez": (booleano true/false, si es su primer empleo formal)
    - "nivel_educativo_maximo": (string, ej: Licenciatura, Maestría, Doctorado, Técnico, Secundaria)
    - "experiencia_total_anios": (número decimal con los años totales de experiencia laboral estimada)

    ---
    OFERTA:
    {texto_oferta}
    ---
    CV:
    {texto_cv}
    ---
    """
    try:
        respuesta = llamar_gemini_con_respaldo(prompt_variables, modelo)
        limpio = respuesta.replace("```json", "").replace("```", "").strip()
        return json.loads(limpio)
    except Exception:
        return {
            "puesto_objetivo": "No especificado",
            "nivel_jerarquico": "No especificado",
            "edad": None,
            "busqueda_primera_vez": False,
            "nivel_educativo_maximo": "No especificado",
            "experiencia_total_anios": 0.0
        }



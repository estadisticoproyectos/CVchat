def generar_archivo_html(texto_cv_mejorado):
    """Convierte el texto markdown del CV mejorado en un documento HTML estilizado y profesional."""
    lineas = texto_cv_mejorado.split("\n")
    html_cuerpo = ""
    for linea in lineas:
        l = linea.strip()
        if not l:
            continue
        if l.startswith("# "):
            html_cuerpo += f"<h1>{l.replace('# ', '')}</h1>\n"
        elif l.startswith("## "):
            html_cuerpo += f"<h2>{l.replace('## ', '')}</h2>\n"
        elif l.startswith("### "):
            html_cuerpo += f"<h3>{l.replace('### ', '')}</h3>\n"
        elif l.startswith("- ") or l.startswith("* "):
            html_cuerpo += f"<li>{l[2:]}</li>\n"
        else:
            html_cuerpo += f"<p>{l}</p>\n"

    html_completo = f"""<!DOCTYPE html>
<html lang="es">
<head>
    <meta charset="UTF-8">
    <title>Currículum Vitae Optimizado</title>
    <style>
        body {{
            font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif;
            line-height: 1.6;
            color: #333;
            max-width: 800px;
            margin: 40px auto;
            padding: 20px;
            background: #fdfdfd;
            border: 1px solid #eaeaea;
            box-shadow: 0 0 10px rgba(0,0,0,0.05);
        }}
        h1 {{
            color: #1a365d;
            border-bottom: 2px solid #2b6cb0;
            padding-bottom: 8px;
            margin-top: 0;
        }}
        h2 {{
            color: #2b6cb0;
            border-bottom: 1px solid #e2e8f0;
            padding-bottom: 5px;
            margin-top: 25px;
        }}
        h3 {{
            color: #2d3748;
            margin-top: 15px;
        }}
        p {{
            margin: 8px 0;
        }}
        li {{
            margin-bottom: 5px;
        }}
    </style>
</head>
<body>
    {html_cuerpo}
</body>
</html>
"""
    return html_completo


def registrar_descarga():
    """Registra la analítica conectándose directamente a PostgreSQL usando los Secrets de Streamlit."""
    st.session_state.descarga_realizada = True
    st.session_state.timestamp_descarga = datetime.datetime.now(datetime.timezone.utc).isoformat()

    # Calcular tiempo transcurrido en segundos desde el inicio del análisis
    if st.session_state.timestamp_inicio:
        tiempo_transcurrido = datetime.datetime.now(datetime.timezone.utc) - st.session_state.timestamp_inicio
        st.session_state.tiempo_sesion_segundos = round(tiempo_transcurrido.total_seconds(), 2)

    try:
        vars_ds = st.session_state.get("variables_cv", {})

        # Leer credenciales de la BD de forma segura desde los Secrets
        db_config = st.secrets["postgres"]

        conexion = psycopg2.connect(
            host=db_config["host"],
            port=db_config["port"],
            user=db_config["user"],
            password=db_config["password"],
            database=db_config["database"],
            sslmode="require"
        )
        cursor = conexion.cursor()

        query = """
            INSERT INTO public.analiticas_avanzadas_cv (
                puesto_objetivo, nivel_jerarquico, edad, busqueda_primera_vez,
                nivel_educativo_maximo, experiencia_total_anios, porcentaje_afinidad,
                afinidad_habilidades, afinidad_experiencia, afinidad_educacion,
                modelo_utilizado, descarga_realizada, timestamp_descarga, tiempo_sesion_segundos
            ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s);
        """

        valores = (
            vars_ds.get("puesto_objetivo"),
            vars_ds.get("nivel_jerarquico"),
            vars_ds.get("edad"),
            vars_ds.get("busqueda_primera_vez"),
            vars_ds.get("nivel_educativo_maximo"),
            vars_ds.get("experiencia_total_anios"),
            st.session_state.porcentaje_afinidad,
            st.session_state.afinidad_secciones.get("Habilidades / Stack Tecnológico"),
            st.session_state.afinidad_secciones.get("Experiencia Laboral"),
            st.session_state.afinidad_secciones.get("Educación y Formación"),
            modelo_gemini,
            True,
            st.session_state.timestamp_descarga,
            st.session_state.tiempo_sesion_segundos
        )

        cursor.execute(query, valores)
        conexion.commit()

        cursor.close()
        conexion.close()

        st.success("✅ ¡Analítica y tiempo de sesión guardados exitosamente en Supabase!")

    except Exception as e:
        st.error(f"❌ Error al conectar o insertar en la BD PostgreSQL: {e}")


